"""Build the self-contained Kaggle kernel for track 1c (Acme grouped weight).

The kernel embeds eval/acme_weight.py and eval/acme_grouped.py (base64), writes
them to /tmp/mombe/eval, imports acme_grouped in-process and runs the grouped
evaluation on the attached dataset. Small results go to /kaggle/working.

Usage: python tools/kaggle/acme_grouped/build_kernel.py
Then:  kaggle kernels push -p tools/kaggle/acme_grouped
"""

from __future__ import annotations

import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SLUG = "thetraveller/mombe-acme-grouped"
DATASET = "sadhliroomyprime/cattle-weight-detection-model-dataset-12k"

TEMPLATE = '''"""Mombe track 1c: Acme grouped weight evaluation (generated by build_kernel.py; edit the sources)."""
import base64, os, subprocess, sys, time
from pathlib import Path

SRC = {SRC}
d = Path("/tmp/mombe/eval")
d.mkdir(parents=True, exist_ok=True)
for name, b64 in SRC.items():
    (d / name).write_bytes(base64.b64decode(b64))
sys.path.insert(0, str(d))
try:
    import cv2  # noqa: F401
except ImportError:
    subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "opencv-python-headless"])
import acme_grouped

t0 = time.time()
root = acme_grouped.find_root("/kaggle/input")
keep = {{}}
rc = acme_grouped.run_grouped(root, Path("/kaggle/working"), workers=os.cpu_count() or 4, keep=keep)
print(f"[kernel] grouped rc={{rc}} in {{time.time() - t0:.0f}} s", flush=True)
if rc != 0:
    raise SystemExit(rc)
# B4 nulls on the acme_weight.py folds: acme_weight.build reads /tmp/mombe/data/acme, linked to the dataset
link = Path("/tmp/mombe/data/acme")
link.parent.mkdir(parents=True, exist_ok=True)
if not link.exists():
    link.symlink_to(root, target_is_directory=True)
# The nulls are a cross-check of the local run; a failure here must not hide the grouped outputs above.
import traceback
try:
    rc = acme_grouped.run_nulls(Path("/kaggle/working"), mine=keep["data"]["B4"], acc=keep["acc"]["B4"])
    print(f"[kernel] nulls rc={{rc}} in {{time.time() - t0:.0f}} s", flush=True)
except BaseException:
    traceback.print_exc()
    print("[kernel] nulls FAILED (grouped outputs are complete)", flush=True)
'''


def main() -> int:
    src = {n: base64.b64encode((ROOT / "eval" / n).read_bytes()).decode() for n in ("acme_weight.py", "acme_grouped.py")}
    (HERE / "kernel.py").write_text(TEMPLATE.replace("{SRC}", json.dumps(src, indent=1)).replace("{{", "{").replace("}}", "}"),
                                    encoding="utf-8")
    meta = {"id": SLUG, "title": "mombe-acme-grouped", "code_file": "kernel.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": True, "dataset_sources": [DATASET], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    print("wrote", HERE / "kernel.py", "and kernel-metadata.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
