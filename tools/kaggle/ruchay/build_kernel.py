def build_cache() -> None:
    """Write the cache kernel to tools/kaggle/ruchay_cache/ (its own slug, so the bench kernel's history stays clean)."""
    import json
    import subprocess
    mb = (ROOT / "mombe" / "body" / "measure.py").read_bytes()
    bb = (ROOT / "eval" / "ruchay_bench.py").read_bytes()
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    src = (CACHE_TEMPLATE.replace("@@MEASURE_B64@@", base64.b64encode(mb).decode())
           .replace("@@BENCH_B64@@", base64.b64encode(bb).decode())
           .replace("@@MEASURE_SHA256@@", hashlib.sha256(mb).hexdigest())
           .replace("@@BENCH_SHA256@@", hashlib.sha256(bb).hexdigest()).replace("@@REPO_COMMIT@@", commit))
    d = HERE.parent / "ruchay_cache"
    d.mkdir(exist_ok=True)
    (d / "kernel.py").write_text(src, encoding="utf-8", newline="\n")
    meta = {"id": "thetraveller/mombe-ruchay-cache", "title": "mombe-ruchay-cache", "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": True, "dataset_sources": [], "competition_sources": [], "kernel_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print("wrote", d / "kernel.py", "bench sha256", hashlib.sha256(bb).hexdigest())


def main() -> None:
    import subprocess
    import sys
    if "--cache" in sys.argv:
        build_cache()
        return
    mb = (ROOT / "mombe" / "body" / "measure.py").read_bytes()
    bb = (ROOT / "eval" / "ruchay_bench.py").read_bytes()
    blob = subprocess.run(["git", "-C", str(ROOT), "hash-object", "mombe/body/measure.py"], capture_output=True, text=True).stdout.strip()
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    src = (TEMPLATE.replace("@@MEASURE_B64@@", base64.b64encode(mb).decode())
           .replace("@@BENCH_B64@@", base64.b64encode(bb).decode())
           .replace("@@MEASURE_SHA256@@", hashlib.sha256(mb).hexdigest())
           .replace("@@MEASURE_BLOB@@", blob).replace("@@REPO_COMMIT@@", commit))
    (HERE / "kernel.py").write_text(src, encoding="utf-8", newline="\n")
    print("wrote", HERE / "kernel.py", "measure sha256", hashlib.sha256(mb).hexdigest(), "blob", blob)


if __name__ == "__main__":
    main()
