def save(Q, view, prep, dst):
    off = Q.mean(0)
    np.savez_compressed(dst, xyz=(Q - off).astype(np.float16), off=off.astype(np.float64), view=view.astype(np.int8),
                        cams=np.asarray(prep["cams_levelled"], np.float64), R=np.asarray(prep["R"], np.float64))
    return hashlib.sha256(open(dst, "rb").read()).hexdigest()


def one(job):
    db, key, ply, mats_path, dst = job
    t0 = time.time()
    try:
        xyz, _ = rb.read_ply(ply)
        mats = rb.parse_matrices(open(mats_path).read()) if mats_path and os.path.exists(mats_path) else None
        P, v, info = rb.split_aligned(xyz, mats)
        prep = rb.prepare(P, v, np.array(info["sentinels"]))
        sha = save(prep["Q"], prep["view"], prep, dst)
        return {"db": db, "id": key, "ok": True, "sha256": sha, "n": int(len(prep["Q"])), "floor": prep["floor"],
                "view_floor": prep["view_floor"], "crop": prep["crop"], "split_info": info, "s": round(time.time() - t0, 1)}
    except Exception as e:
        traceback.print_exc()
        return {"db": db, "id": key, "ok": False, "reason": f"{type(e).__name__}: {e}"}


